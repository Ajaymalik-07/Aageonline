/**
 * AageOnline — Append-Only Position History Domain
 *
 * Implements authoritative audit trail of all paid visibility position mutations:
 * - Append-only, strictly immutable records
 * - Auditable cause: PAID_VISIBILITY_SETTLEMENT
 * - Direct traceability to paymentOrderId, bidIntentId, and rankingSettlementId
 * - No-op movements generate ZERO history records
 */

import type { PositionHistoryRecord } from '../../types/ranking-settlement.ts';

const POSITION_HISTORY_STORE: PositionHistoryRecord[] = [];

/**
 * Appends an immutable PositionHistoryRecord to the audit trail.
 */
export function appendPositionHistoryRecord(
  record: PositionHistoryRecord
): PositionHistoryRecord {
  // Disallow no-op records
  if (record.previousPosition !== null && record.previousPosition === record.newPosition) {
    throw new Error(
      `Cannot create PositionHistoryRecord for no-op transition (${record.previousPosition} -> ${record.newPosition}).`
    );
  }

  const frozen = Object.freeze({ ...record });
  POSITION_HISTORY_STORE.push(frozen);
  return frozen;
}

/**
 * Retrieves all position history records for a business, sorted newest first.
 */
export function getPositionHistoryByBusiness(
  businessId: string
): PositionHistoryRecord[] {
  return POSITION_HISTORY_STORE.filter((r) => r.businessId === businessId).sort(
    (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
  );
}

/**
 * Retrieves all position history records for a market, sorted newest first.
 */
export function getPositionHistoryByMarket(
  marketId: string
): PositionHistoryRecord[] {
  return POSITION_HISTORY_STORE.filter((r) => r.marketId === marketId).sort(
    (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
  );
}

/**
 * Retrieves position history records generated by a specific ranking settlement.
 */
export function getPositionHistoryBySettlement(
  rankingSettlementId: string
): PositionHistoryRecord[] {
  return POSITION_HISTORY_STORE.filter(
    (r) => r.rankingSettlementId === rankingSettlementId
  );
}

/**
 * Total count of position history records.
 */
export function getPositionHistoryCount(): number {
  return POSITION_HISTORY_STORE.length;
}

/**
 * Snapshots the position history store for transaction rollback support.
 */
export function clonePositionHistoryStore(): PositionHistoryRecord[] {
  return [...POSITION_HISTORY_STORE];
}

/**
 * Restores the position history store to a previous snapshot during rollback.
 */
export function restorePositionHistoryStore(
  snapshot: PositionHistoryRecord[]
): void {
  POSITION_HISTORY_STORE.length = 0;
  POSITION_HISTORY_STORE.push(...snapshot);
}

/**
 * Clears the position history store for testing.
 */
export function resetPositionHistoryStoreForTesting(): void {
  POSITION_HISTORY_STORE.length = 0;
}
